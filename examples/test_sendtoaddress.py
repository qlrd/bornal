def test_000_index(alice, bob):
    connect_p2p(alice, bob)
    assert_chain(alice, "regtest")
    assert_chain(bob, "regtest")


def test_001_create_wallets(alice, bob):
    create_wallet(alice, "alice-wallet")
    create_wallet(bob, "bob-wallet")
    assert_wallet_info(alice, "alice-wallet")
    assert_wallet_info(bob, "bob-wallet")


def test_002_fund_alice(alice, bob, state):
    assert_block_count(alice, 0)
    assert_block_count(bob, 0)
    address = get_new_address(alice, "test_sendtoaddress::alice")
    generate_to_address(alice, address, COINBASE_MATURITY + 1)
    sync_blocks(alice, bob)
    assert_block_count(alice, COINBASE_MATURITY + 1)
    assert_block_count(bob, COINBASE_MATURITY + 1)
    wait_wallet_synced(alice)
    balance = alice.client.get_balance()
    assert balance >= BASE_COINBASE_SUBSIDY, f"alice balance too low: {balance}"
    state["alice_balance"] = balance


def test_003_send_to_bob(alice, bob, state):
    address = get_new_address(bob, "test_sendtoaddress::bob")
    txid = alice.client.send_to_address(address, AMOUNT)
    mempool = alice.client.get_raw_mempool()
    assert txid in mempool, f"'{txid}' should be in alice's mempool, got {mempool}"
    state["bob_address"] = address
    state["txid"] = txid


def test_004_sync_with_bob(alice, bob):
    generate_to_address(alice, UNSPENDABLE_ADDRESS, 1)
    sync_blocks(alice, bob)
    assert_block_count(bob, COINBASE_MATURITY + 2)
    wait_wallet_synced(alice)
    wait_wallet_synced(bob)


def test_005_fund_bob(alice, bob, state):
    tx = alice.client.get_transaction(state["txid"])
    assert tx["confirmations"] == 1, f"Expected 1 confirmation, got {tx}"

    received = bob.client.get_received_by_address(state["bob_address"])
    assert received == AMOUNT, f"bob should receive {AMOUNT}, got {received}"
    balance = bob.client.get_balance()
    assert balance == AMOUNT, f"bob balance should be {AMOUNT}, got {balance}"

    # alice spent AMOUNT plus fee (``fee`` is negative), but one more of her
    # coinbases matured with the new block
    expected = round(
        state["alice_balance"] - AMOUNT + tx["fee"] + BASE_COINBASE_SUBSIDY, 8
    )
    alice_balance = round(alice.client.get_balance(), 8)
    assert alice_balance == expected, (
        f"alice balance should be {expected}, got {alice_balance}"
    )
